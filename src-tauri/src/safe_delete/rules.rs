// Declarative rule engine — chapters 6.1, 6.2 (target: 50+ rules).
// v0.1 phase 1: ~30 rules, Name + Extension patterns.
// v0.2: path-context (path hints from ancestors), glob (chapter 6.4 user rules).

#[derive(Debug, Clone, Copy)]
pub enum Pattern {
    /// Full name match (case-insensitive).
    Name(&'static str),
    /// File extension (`.tmp`, `.log`). Never applies to directories.
    Extension(&'static str),
}

#[derive(Debug, Clone, Copy)]
pub struct Rule {
    pub id: &'static str,
    pub pattern: Pattern,
    /// 0-100. Higher = safer to delete (chapter 6.3).
    pub score: u8,
    pub explanation: &'static str,
}

